export function countryLabel(code) {
  return countryNames[code] || code.toUpperCase()
}

export function categoryLabel(slug) {
  return categoryNames[slug] || slug
}

export async function loadMeta() {
  const res = await fetch('/catalog/meta.json')
  if (!res.ok) throw new Error('Katalog yüklenemedi')
  return res.json()
}

export async function loadCountry(code) {
  const res = await fetch(`/catalog/countries/${code}.json`)
  if (!res.ok) throw new Error('Ülke listesi yüklenemedi')
  return res.json()
}

export async function loadCategory(slug) {
  const res = await fetch(`/catalog/categories/${slug}.json`)
  if (!res.ok) throw new Error('Kategori listesi yüklenemedi')
  return res.json()
}

export async function loadAllChannels() {
  const res = await fetch('/catalog/all.json')
  if (!res.ok) throw new Error('Tüm kanal listesi yüklenemedi')
  return res.json()
}
